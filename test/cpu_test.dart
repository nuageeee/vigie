void main() {
  group('parseCpu', () {
    test('returns idle and total for one CPU', () {
      final cpu = parseCpu(headExit);
      expect(cpu['cpu0'], (85725347, 86456629));
    });
    test('reads every line', () {
      final cpu = parseCpu(headExit);
      expect(cpu, hasLength(9));
    });
    test('ignores non-CPU lines', () {
      final cpu = parseCpu(headExit);
      expect(cpu['intr'], isNull);
    });
